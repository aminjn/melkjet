// ── ارقامِ فارسی/عربی → لاتین (فاز ۲۷۶) ─────────────────────────────────────
// چرا لازم شد (فیدبکِ کاربر: «شماره را از دیوار کپی می‌کنیم کار نمی‌کند»):
// همه‌جای پروژه ورودیِ عددی با `replace(/\D/g, '')` تمیز می‌شد. `\D` یعنی «هر چیزی که
// رقمِ لاتین نیست» — پس «۰۹۱۵۵۵۵۷۴۸۲»ی که کاربر از دیوار کپی می‌کند کاملاً **پاک**
// می‌شد و فیلد خالی می‌ماند (نه خطا، نه هشدار؛ فقط کار نمی‌کرد). دیوار همهٔ اعداد را
// فارسی نشان می‌دهد، پس این عملاً یعنی «کپی از دیوار هرگز کار نمی‌کند».
//
// راهِ حل: قبل از هر پاک‌سازی، ارقام را به لاتین ترجمه کن. الگوی مصرف در همهٔ کد:
//   value.replace(FA_DIGITS, faDigit).replace(/\D/g, '')
// یا برای کدِ جدید، مستقیم:  digitsOnly(value)
//
// شاملِ ارقامِ فارسی (۰۶F0–۰۶F9) و عربیِ هندی (۰۶۶۰–۰۶۶۹) — هر دو در متنِ آگهی‌ها دیده می‌شوند.
// جداکننده‌های فارسی (٬ و ٫) هم به شکلِ لاتین برمی‌گردند تا «۸٬۵۰۰٬۰۰۰» درست خوانده شود.

const FA = '۰۱۲۳۴۵۶۷۸۹'
const AR = '٠١٢٣٤٥٦٧٨٩'

export const FA_DIGITS = /[۰-۹٠-٩٬٫]/g

export function faDigit(d: string): string {
  const i = FA.indexOf(d)
  if (i >= 0) return String(i)
  const j = AR.indexOf(d)
  if (j >= 0) return String(j)
  return d === '٬' ? ',' : d === '٫' ? '.' : d
}

// ترجمهٔ ارقام، بدونِ حذفِ چیزِ دیگر («۰۹۱۲-۳۴۵» → «0912-345»).
export const enDigits = (s: unknown): string => String(s ?? '').replace(FA_DIGITS, faDigit)

// فقط رقم‌ها، پس از ترجمه («۰۹۱۵ ۵۵۵ ۷۴۸۲» → «09155557482»).
export const digitsOnly = (s: unknown): string => enDigits(s).replace(/\D/g, '')

// نخستین عددِ صحیحِ یک متن، با احترام به جداکنندهٔ هزارگان (۱۹ سپتامبر).
//
// چرا لازم شد: دو نسخهٔ محلیِ firstInt وجود داشت — یکی در listing-search با
// /(\d{1,4})/ و یکی در listing-similarity که فقط کامایِ لاتین را می‌شناخت. متراژِ
// «۴٬۰۰۰ متر» می‌شد ۴ متر، چون «٬» رقم نیست و تطبیق همان‌جا قطع می‌شد. ۸۹ آگهیِ
// عمومی با این وضع پیدا شد: «۴۰۰۰ متر مستغلات» با متراژِ ۴، و متریِ ۱۱۵۰۰۰۰ میلیون.
//
// آن عدد فقط عدد نیست: عنوانِ سئو، فیلترِ متراژ، متریِ تحلیل، امتیازِ اصالت و
// کلیدِ تشخیصِ تکراری همه روی همین ساخته می‌شوند.
//
// lookbehind عمداً به‌کار نرفته: این ماژول در باندلِ کلاینت هم می‌رود و سافاریِ
// قدیمی‌تر از ۱۶٫۴ با دیدنِ lookbehind کلِ فایل را رد می‌کند.
export function intFrom(s: unknown, maxDigits = 7): number | null {
  const t = enDigits(s).replace(/(\d)[,\s\u00A0\u2009](?=\d{3}(?!\d))/g, '$1')
  const m = t.match(new RegExp('\\d{1,' + maxDigits + '}'))
  return m ? parseInt(m[0], 10) : null
}
