/** آزمونِ مثبت: یک تا سه توکنِ فارسی، بدونِ رقم/علامت/کشیده، و یا نامِ کوچکِ شناخته‌شده
 *  در ابتدا یا پسوندِ نام‌خانوادگی در انتها. امضای برندِ لاتین هم پذیرفته می‌شود. */
/** آزمونِ ساختاری‌محض: نام باید شکلِ نام داشته باشد — ولی «شناخته‌شده» بودن شرط نیست.
 *  فهرستِ نامِ کوچک فقط برای نجاتِ کاندیدا در برابرِ واژه‌نامهٔ پیکره به کار می‌رود،
 *  نه به‌عنوان دروازه؛ وگرنه هر نامِ نادیده قربانی می‌شد. */
export function looksLikeName(v: string): boolean {
  const s = String(v || '').replace(/\u0640/g, '').replace(/\s+/g, ' ').trim()
  if (!s) return false
  if (/[0-9\u06f0-\u06f9:\uff1a.\u066c\u060c\u061b]/.test(s)) return false
  if (/^[A-Za-z][A-Za-z ]{2,23}$/.test(s)) return true
  const ws = s.split(' ').filter(Boolean)
  if (!ws.length || ws.length > 3) return false
  return ws.every(w => /^[\u0621-\u06cc\u200c]{2,}$/.test(w))
}

/** فقط برای نجات: اگر توکنِ اول نامِ کوچکِ شناخته‌شده باشد، واژه‌نامهٔ پیکره ردش نمی‌کند. */
export function hasKnownFirstName(v: string): boolean {
  const w = String(v || '').trim().split(/\s+/)[0] || ''
  return FIRST_NAMES.has(keyOf(w))
}

