const STOP_K = new Set([...STOPWORDS].map(keyOf))
const DIGIT = /[0-9۰-۹]/

// آیا این «کلمه» نوفه است (نه جزئی از نامِ آدم)؟
export function isNoiseWord(w: string): boolean {
  const k = keyOf(w)
  if (!k) return true
  if (TITLES.has(k) || STOPWORDS.has(w) || STOP_K.has(k) || REALTY_TOKENS.has(k) || ADDR_MARKERS.has(k)) return true
  if (DIGIT.test(k)) return true                                    // «۹۵متری»، «۴۱»
  if (/^(تک|یک|دو|سه|چهار|پنج|شش)?خوابه?$/.test(k)) return true      // «دوخواب/سه‌خوابه»
  if (/(متری|متراژ|خوابه)$/.test(k)) return true
  // حرفِ اضافهٔ چسبیده به واژهٔ نوفه: «باهماهنگی»، «بااحترام»، «جهتهماهنگی»
  const m = k.match(/^(با|به|در|از|جهت|برای)(.{3,})$/)
  if (m && (STOP_K.has(m[2]) || REALTY_TOKENS.has(m[2]) || ADDR_MARKERS.has(m[2]))) return true
  return false
}

// مرزِ «قطعه»: آدرس در همین قطعه تمام می‌شود، پس «منطقه ۲: رضایی» رضایی را آلوده نمی‌کند.
const SEG_SPLIT = /[\n\r,،؛;:：|()[\]«»"'\-–—]+/

// توکن‌هایی که «نامِ معبر»اند: تا ۲ کلمه پس از هر نشانهٔ آدرس، تا رسیدن به رقم/نشانهٔ بعدی/مرزِ قطعه.
// خروجی = مجموعهٔ کلیدها؛ هر کاندیدای نامی که کلیدش این‌جا باشد، برای همان آگهی رد می‌شود.
const SMALL_NUM = /^[0-9۰-۹]{1,3}$/
export function addressTokens(text: string): Set<string> {
  const out = new Set<string>()
  for (const seg of deEmoji(String(text || '')).split(SEG_SPLIT)) {
    const ws = seg.trim().split(/\s+/).filter(Boolean)
    for (let i = 0; i < ws.length; i++) {
      // (الف) «کلمهٔ فارسی + عددِ کوچک» = پلاک/شمارهٔ معبر. نمونهٔ واقعی: «(فلاحی 38)» که هیچ
      //       نشانهٔ آدرسی قبلش نداشت و مشاورِ جعلیِ «فلاحی» می‌ساخت. عددِ بلند (موبایل) شمرده نمی‌شود.
      if (i + 1 < ws.length && SMALL_NUM.test(ws[i + 1]) && !DIGIT.test(keyOf(ws[i]))) out.add(keyOf(ws[i]))
      // (ب) تا ۲ کلمه پس از نشانهٔ صریحِ آدرس («بین فلاحی ۴۱ و ۴۳»).
      if (!ADDR_MARKERS.has(keyOf(ws[i]))) continue
      for (let j = i + 1; j <= i + 2 && j < ws.length; j++) {
        const k = keyOf(ws[j])
        if (!k || DIGIT.test(k)) break            // «فلاحی ۴۱» → عدد یعنی پایانِ نامِ معبر
        if (ADDR_MARKERS.has(k)) break            // شروعِ آدرسِ بعدی
        out.add(k)
      }
    }
  }
  return out
}

// پاک‌سازیِ نام: حذفِ القاب و کلماتِ نوفه/ملکی/آدرس از ابتدا و میانِ کاندیدا.
export function cleanName(s: string): string {
  return s.split(/\s+/).filter(Boolean).filter(w => !isNoiseWord(w)).join(' ').trim()
}

// آیا این کاندیدا نامِ واقعیِ شخص/برند است یا نوفه؟
export function isBadName(v: string): boolean {
  const words = v.split(/\s+/).filter(Boolean)
  if (!words.length) return true
  if (words.some(w => w.length < 2)) return true                       // تکه‌های تک‌حرفی مثل «ی تایید»
  if (words.length >= 2 && words.every(w => w.length <= 2)) return true // تکه‌های کوتاهِ مثلِ «ان ما»
  if (words.length > 3) return true                                     // جملهٔ تبلیغاتی، نه اسم
  if (REALTY_TOKENS.has(keyOf(v))) return true                          // کلِ نام یک واژهٔ ملکی است
  if (words.some(w => isNoiseWord(w))) return true                      // حتی یک کلمهٔ نوفه = اسم نیست
  if (/^\d+$/.test(keyOf(v))) return true
  return false
}

// نامِ نهاییِ معتبر یا خالی: پاک‌سازیِ القاب/نوفه + ردِ نامِ خراب + ردِ نامِ خودِ آژانس
// + (فاز ۲۷۵) ردِ هر کاندیدایی که توکنِ آدرسِ همان آگهی باشد.
export function validName(s: string, agencyName = '', banned?: Set<string>): string {
  const v = cleanName((s || '').trim())
  if (!v || v.length < 2 || v.length > 24 || isBadName(v)) return ''
  const k = keyOf(v), a = keyOf(agencyName)
  if (a && k.length >= 2 && (k === a || a.includes(k) || k.includes(a))) return ''   // خودِ آژانس امضا نیست
  if (banned?.size && v.split(/\s+/).some(w => banned.has(keyOf(w)))) return ''      // «فلاحی» از «بین فلاحی ۴۱»
  return v
}

// ── نامِ «سالمِ کامل»: هیچ کلمه‌ای از آن حذف نشده باشد (فاز ۲۷۵b) ─────────────
// چرا لازم شد: `validName` نام را پاک‌سازی می‌کند و باقی‌مانده را برمی‌گرداند، پس «قدیمی منطقه»
// می‌شود «قدیمی» و غیرخالی است. با شرطِ سستِ `if (validName(x))` چنین آشغالی از دروازهٔ یادگیری
// رد می‌شد و در واژه‌نامهٔ تولید با وزنِ ۵۸۸ نشسته بود («نزدیک مترو» با وزنِ ۴۰۰ هم همین‌طور).
// برای «ذخیره/یادگیریِ» یک نام باید سخت‌گیر بود: کوچک‌ترین دست‌خوردگی = این اصلاً اسم نبوده.
export function strictName(s: string, agencyName = '', banned?: Set<string>): string {
  const raw = String(s || '').trim().replace(/\s+/g, ' ')
  const v = validName(raw, agencyName, banned)
  return v && v === raw ? v : ''
}

// آیا این «خط» فقط یک نامِ آدم است؟ («▪ مصطفی هوشمند» → «مصطفی هوشمند»)
// سخت‌گیرانه: هیچ کلمهٔ نوفه/رقم/آدرسی نباید داشته باشد و حداکثر ۲ کلمه باشد.
export function bareNameLine(line: string, minWords = 1, agencyName = '', banned?: Set<string>): string {
  const ws = deEmoji(line || '').trim().split(/\s+/).filter(Boolean)
    .filter(w => !TITLES.has(keyOf(w)))            // «آقای رضایی» → «رضایی»
  if (ws.length < minWords || ws.length > 2) return ''
  if (ws.some(w => isNoiseWord(w) || w.length < 2)) return ''
  return validName(ws.join(' '), agencyName, banned)
}
