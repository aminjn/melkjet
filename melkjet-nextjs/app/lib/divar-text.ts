// فاز ۳۴۴ (پورت از خودروجت، فاز ۳۵۱–۳۵۲) — «متادیتای انتشارِ دیوار» هرگز توضیحاتِ آگهی نیست.
// دیوار در آگهیِ به‌روزشده/نردبان‌شده یک ویجتِ توضیحات زیرِ عنوان دارد: «انتشار آگهی: ۱۱ آذر ۱۴۰۴، ۱۲:۴۳ /
// آخرین نردبان: ۷ آبان ۱۴۰۵، ۱۱:۵۷». اگر جای «متنِ فروشنده» بنشیند، رُستر امضای مشاور را نمی‌بیند و AI روی
// یک تاریخ تصمیم می‌گیرد. تشخیص «ساختاری» است نه فهرستِ برچسب: هر خطِ «برچسبِ کوتاه: تاریخ/ساعت» (ماهِ شمسی +
// سال، hh:mm، «… پیش»، امروز/دیروز) متادیتاست — برچسبِ تازهٔ دیوار هم بی‌تغییرِ کد گرفته می‌شود.
// خالص (بدونِ I/O) تا پارسرِ دیوار، رُستر و پنل از یک قاعده بخوانند.
const META_LINE = /^(?:انتشار(?:\s*آگهی)?|منتشر\s*شده|تاریخ\s*(?:انتشار|ثبت)|زمان\s*(?:انتشار|ثبت)|آخرین\s*به\s*روز\s*رسانی|به\s*روز\s*رسانی|بروز\s*رسانی|آخرین\s*بروزرسانی|(?:آخرین\s*)?نردبان(?:\s*شده)?|کد\s*آگهی|شناسه\s*آگهی)(?:\s*[:：]|\s+[\d۰-۹])/
const FA_MONTH = '(?:فروردین|اردیبهشت|خرداد|تیر|مرداد|شهریور|مهر|آبان|آذر|دی|بهمن|اسفند)'
const DATE_VALUE = new RegExp(`^(?:[\\d۰-۹]{1,2}\\s*${FA_MONTH}(?:\\s*[\\d۰-۹]{2,4})?|[\\d۰-۹]{4}[/\\-][\\d۰-۹]{1,2}[/\\-][\\d۰-۹]{1,2}|[\\d۰-۹]{1,2}:[\\d۰-۹]{2}|(?:[\\d۰-۹]+\\s*)?(?:لحظاتی|دقایقی|ساعاتی|دقیقه|ساعت|روز|هفته|ماه|سال)\\s*(?:پیش|قبل)|امروز|دیروز)(?:\\s*[،,]?\\s*(?:ساعت\\s*)?[\\d۰-۹]{1,2}:[\\d۰-۹]{2})?$`)
const LABELED_DATE = /^([^:：\n]{2,30})\s*[:：]\s*(.+)$/
function isMetaLine(l: string): boolean {
  if (l.length > 80) return false
  if (META_LINE.test(l)) return true
  const m = l.match(LABELED_DATE)
  return !!m && !/[\d۰-۹]{5,}/.test(m[1]) && DATE_VALUE.test(m[2].trim())
}
/** آیا این متن «فقط» متادیتای انتشارِ دیوار است؟ (حداکثر ۴ خط و همه متادیتا) */
export function isDivarMetaText(s: string | undefined | null): boolean {
  const lines = String(s || '').replace(/[‌‏‎]/g, ' ').split(/\n+/).map(l => l.replace(/\s+/g, ' ').trim()).filter(Boolean)
  return lines.length > 0 && lines.length <= 4 && lines.every(isMetaLine)
}
