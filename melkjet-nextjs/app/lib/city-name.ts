// نامِ «کانونیِ» شهر — نشان یک شهر را همه‌جا یک‌جور ذخیره/مقایسه می‌کنیم.
// باگِ زنده (۲۸ اکتبر): ژئوکدِ معکوسِ نشان شهر را «شهر تهران» برمی‌گرداند؛ تشخیصِ خودکارِ موقعیت آن را در
// کوکیِ mj_city می‌نوشت و جستجو دنبالِ آگهی‌هایی می‌گشت که موقعیتشان «شهر تهران» را دارد → صفر آگهی
// («هنوز آگهی‌ای ثبت نشده» در کلِ سایت برای هر کسی که دسترسیِ موقعیت داده بود).
export function canonCity(s: string | null | undefined): string {
  const t = String(s || '').replace(/ي/g, 'ی').replace(/ك/g, 'ک').replace(/\s+/g, ' ').trim()
  // «شهر ری» و «شهرِ قدس» خودشان نامِ شهرند (و «ری» به‌تنهایی زیررشتهٔ «شهریار» است) — دست نخورند.
  if (/^شهر\s*ری$/.test(t)) return 'شهر ری'
  return t.replace(/^(?:شهرستان|شهر\s+جدید|شهر|استان|کلان\s*شهر)\s+/, '').trim()
}
